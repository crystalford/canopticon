/* WORLDS — the text universes a film can be made of.
 *
 * "The monotype collage is one of maybe thousands."
 *
 * Correct. What existed was one world with parameters, and calling its five
 * registers "different kinds of page" was generous — they were all type on a
 * photocopied sheet. A world is a bigger thing than a register: it owns a FACE
 * SET, a TREATMENT vocabulary, a LAYOUT vocabulary, a motion character and a
 * material character. Two worlds do not look like the same film with the dials
 * moved, because they are not built out of the same operations.
 *
 * TEXT THROUGHOUT. No imagery, no photographs, nothing generated by a model.
 * Every one of these is made only of the essay's own words, set differently.
 * That constraint is the operator's and it is not a limitation to work around
 * — a typographic universe is a real place and there are thousands of them.
 *
 * WHY THIS IS STILL NOT THE NOUN→PICTURE MENU. Nothing here reads a subject,
 * a topic or a noun. A world is chosen from position in the film and from
 * section structure, and everything inside it is generated from the writing.
 * The failure four rebuilds produced was "this sentence is about a camera, so
 * draw a camera". No sentence reaches this file.
 */

