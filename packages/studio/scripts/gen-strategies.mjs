// Generates lab/strategies.js from experiments/strategy.ts.
//
// The Lab is a static page with no build step, so it cannot import the
// compiler's modules. Rather than hand-copy the eight strategies into the
// UI — which is exactly how the Lab and the Worker came to disagree about
// 57 of 88 scenes — the descriptors are generated, and a drift shows up as
// a diff rather than as a wrong label in the product.
import { writeFileSync } from "node:fs";
import { STRATEGIES } from "../experiments/strategy.ts";

const rows = Object.values(STRATEGIES).map((s) => ({
  id: s.id,
  name: s.name,
  feels: s.feels,
  argument: s.argument,
}));
writeFileSync(
  new URL("../lab/strategies.js", import.meta.url),
  `/* GENERATED by scripts/gen-strategies.mjs — do not edit.\n * Source of truth: experiments/strategy.ts */\nconst STRATEGIES_UI = ${JSON.stringify(rows, null, 2)};\n`,
);
console.log(`wrote lab/strategies.js — ${rows.length} strategies`);
