// Generates lab/languages.js from the compiler's own LANGUAGE table.
//
// The five visual languages are REAL — `construct.ts` uses them to move
// every operator's appetite and to set the representation rung a
// construction prefers — and until the product pass there was no surface
// anywhere that could change one. Now that VISUAL can, the list it offers
// has to be the compiler's list, not a copy of it: a picker naming a sixth
// language, or omitting one, is the same class of bug as the Lab and the
// Worker disagreeing about 57 of 88 scenes.
//
// The director-facing name and the plain sentence are here rather than in
// construct.ts because they are product copy about a compiler fact, and
// the compiler's own `why` is carried through underneath them verbatim.
import { writeFileSync } from "node:fs";
import { LANGUAGE } from "../src/compile/construct.ts";

/** What a director is told each one is. Keyed by the compiler's own ids —
 *  a language added to `construct.ts` without a line here fails the build
 *  below rather than appearing in the product as a bare identifier. */
const COPY = {
  documentary: {
    name: "Documentary",
    feels: "observed, physical, in a place",
    blurb:
      "Things are photographed rather than diagrammed. Grade and grain do the work; nothing is broken apart.",
  },
  technical: {
    name: "Technical",
    feels: "measured, drawn, specified",
    blurb:
      "The film reads like a specification — line, threshold and trace, with the softness taken out.",
  },
  pixel: {
    name: "Pixel",
    feels: "low-resolution, synthetic, quantised",
    blurb: "Everything is resolved to a grid and a small palette. Deliberately made, not captured.",
  },
  surreal: {
    name: "Surreal",
    feels: "unstable, coming apart",
    blurb:
      "Things are allowed to fragment and re-sort into their own structure. The most abstract of the five.",
  },
  kinetic: {
    name: "Kinetic",
    feels: "fast, cut hard, in motion",
    blurb: "Motion and the cut carry the argument. Traces and splits over stillness.",
  },
};

const rows = Object.entries(LANGUAGE).map(([id, bias]) => {
  const copy = COPY[id];
  if (!copy) {
    throw new Error(
      `construct.ts declares the visual language "${id}" and scripts/gen-languages.mjs has no director-facing copy for it. Add it rather than shipping a bare identifier.`,
    );
  }
  return { id, ...copy, why: bias.why, representation: bias.representation };
});
for (const id of Object.keys(COPY)) {
  if (!LANGUAGE[id])
    throw new Error(`copy exists for "${id}" but construct.ts has no such language`);
}

writeFileSync(
  new URL("../lab/languages.js", import.meta.url),
  `/* GENERATED by scripts/gen-languages.mjs — do not edit.\n * Source of truth: src/compile/construct.ts */\nconst LANGUAGES_UI = ${JSON.stringify(rows, null, 2)};\n`,
);
console.log(`wrote lab/languages.js — ${rows.length} visual languages`);
