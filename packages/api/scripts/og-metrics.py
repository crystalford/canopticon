#!/usr/bin/env python3
"""Write src/site/og/metrics.ts: Geist's advance widths for the share cards.

The card is SVG rendered by resvg, which does not wrap text, so og.ts wraps
it itself and needs to know how wide each character is. This reads the real
widths from the vendored fonts (units per em = 1000) for printable ASCII and
the punctuation the record uses. Anything not in the table is measured as an
average character. Re-run after changing a font:

    pip install fonttools && python3 scripts/og-metrics.py && pnpm exec biome format --write src/site/og/metrics.ts
"""

import json

from fontTools.ttLib import TTFont

CHARS = "".join(chr(c) for c in range(32, 127)) + "–—‘’“”…·€£°×→éèêàçôöüñ"
OUT = "src/site/og/metrics.ts"


def widths(weight: str) -> dict[str, int]:
    font = TTFont(f"src/site/og/fonts/Geist-{weight}.ttf")
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    out = {}
    for ch in CHARS:
        glyph = cmap.get(ord(ch))
        if glyph:
            out[ch] = hmtx[glyph][0]
    return out


def main() -> None:
    lines = [
        "// Generated by scripts/og-metrics.py from the vendored Geist fonts — do not edit.",
        "// Advance widths in 1/1000 em, for wrapping the share card's text (og.ts).",
        "",
    ]
    for weight in ("Regular", "Medium", "SemiBold"):
        w = widths(weight)
        chars = "".join(w.keys())
        nums = ",".join(str(v) for v in w.values())
        lines.append(f"export const {weight.upper()}_CHARS = {json.dumps(chars, ensure_ascii=False)};")
        lines.append(f"export const {weight.upper()}_WIDTHS = [{nums}];")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
