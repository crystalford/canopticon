import { db, articles } from '@/db'
import { desc, eq } from 'drizzle-orm'
import Link from 'next/link'
import { Edit, ExternalLink, MoreHorizontal, FileText, UserCog } from 'lucide-react'
import { formatDistanceToNow } from 'date-fns'
import { ArticleActions } from '@/components/content/ArticleActions'

export const dynamic = 'force-dynamic'

export default async function ContentPage() {
    const allArticles = await db.query.articles.findMany({
        orderBy: [desc(articles.createdAt)],
    })

    return (
        <div className="max-w-5xl mx-auto py-12 px-6">
            <div className="flex items-center justify-between mb-8">
                <div>
                    <h1 className="text-3xl font-bold text-white mb-2">Articles</h1>
                    <p className="text-slate-400">Published articles and drafts generated by your pipelines.</p>
                </div>
                {/* Could add 'New Article' button here if manual creation is desired */}
            </div>

            <div className="bg-white/[0.03] border border-white/[0.08] rounded-xl overflow-hidden">
                <table className="w-full text-left text-sm">
                    <thead className="bg-white/[0.05] text-slate-400 uppercase text-xs font-medium">
                        <tr>
                            <th className="px-6 py-4">Article</th>
                            <th className="px-6 py-4">Status</th>
                            <th className="px-6 py-4">Date</th>
                            <th className="px-6 py-4 text-right">Actions</th>
                        </tr>
                    </thead>
                    <tbody className="divide-y divide-white/[0.05]">
                        {allArticles.length === 0 ? (
                            <tr>
                                <td colSpan={4} className="px-6 py-12 text-center text-slate-500">
                                    No articles found. Start a chat investigation to generate one.
                                </td>
                            </tr>
                        ) : (
                            allArticles.map((article) => (
                                <tr key={article.id} className="hover:bg-white/[0.02] transition-colors group">
                                    <td className="px-6 py-4 max-w-lg">
                                        <div className="font-medium text-white mb-1 truncate" title={article.title}>
                                            {article.title}
                                        </div>
                                        <div className="flex flex-wrap gap-1">
                                            {article.tags?.slice(0, 3).map((tag: string) => (
                                                <span key={tag} className="text-[10px] px-1.5 py-0.5 rounded bg-white/[0.05] text-slate-500">
                                                    {tag}
                                                </span>
                                            ))}
                                        </div>
                                    </td>
                                    <td className="px-6 py-4">
                                        <span className={`inline-flex items-center px-2 py-1 rounded-full text-xs font-medium border ${article.status === 'published'
                                            ? 'bg-green-500/10 border-green-500/20 text-green-400'
                                            : 'bg-yellow-500/10 border-yellow-500/20 text-yellow-400'
                                            }`}>
                                            {article.status === 'published' ? 'Published' : 'Draft'}
                                        </span>
                                    </td>
                                    <td className="px-6 py-4 text-slate-500">
                                        {formatDistanceToNow(new Date(article.createdAt), { addSuffix: true })}
                                    </td>
                                    <td className="px-6 py-4 text-right">
                                        <ArticleActions
                                            articleId={article.id}
                                            slug={article.slug}
                                            status={article.status as 'draft' | 'published'}
                                        />
                                    </td>
                                </tr>
                            ))
                        )}
                    </tbody>
                </table>
            </div>
        </div>
    )
}
